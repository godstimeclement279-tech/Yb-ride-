function makeBooking(partial: Partial<Booking> & Pick<Booking, 'id' | 'status' | 'createdAt'>): Booking {
  const passenger = mockPassengers[0]!;
  const distanceKm = partial.fare?.estimatedDistanceKm ?? 6.4;
  const carType = mockCarTypes.find((c) => c.id === (partial.carTypeId ?? 'ct-standard'))!;
  const baseFare = carType.baseFare;
  const distanceFare = Math.round(carType.pricePerKm * distanceKm);
  const zoneSurcharge = partial.fare?.zoneSurcharge ?? 0;
  return {
    id: partial.id,
    passengerId: partial.passengerId ?? passenger.id,
    pickup: partial.pickup ?? {
      label: 'Home',
      formatted: '12 Market Rd, Agbor',
      point: { latitude: 6.215, longitude: 6.198 },
    },
    dropoff: partial.dropoff ?? {
      label: 'Work',
      formatted: 'Delta State University, Abraka',
      point: { latitude: 6.225, longitude: 6.211 },
    },
    isRoundTrip: partial.isRoundTrip ?? false,
    carTypeId: carType.id,
    fare: partial.fare ?? {
      baseFare,
      distanceFare,
      zoneSurcharge,
      total: baseFare + distanceFare + zoneSurcharge,
      estimatedDistanceKm: distanceKm,
      estimatedDurationMin: Math.round(distanceKm * 2.4),
      currency: 'NGN',
      carTypeId: carType.id,
      carTypeName: carType.name,
      appliedZoneIds: zoneSurcharge ? ['zn-airport'] : [],
    },
    status: partial.status,
    driverId: partial.driverId,
    staffAssignedBy: partial.staffAssignedBy,
    createdAt: partial.createdAt,
    paidAt: partial.paidAt,
    assignedAt: partial.assignedAt,
    driverArrivedAt: partial.driverArrivedAt,
    startedAt: partial.startedAt,
    completedAt: partial.completedAt,
    cancelledAt: partial.cancelledAt,
    cancellationReason: partial.cancellationReason,
    cancelledBy: partial.cancelledBy,
    paystackReference: partial.paystackReference,
    paymentMethod: partial.paymentMethod,
    actualDistanceKm: partial.actualDistanceKm,
    actualDurationMin: partial.actualDurationMin,
    ratingFromPassenger: partial.ratingFromPassenger,
    ratingFromDriver: partial.ratingFromDriver,
  };
}

